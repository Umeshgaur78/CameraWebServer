"""
get_model.py
============
Dog + Car detection model download karke model_data.h generate karta hai.

USAGE:
  python get_model.py

REQUIREMENTS:
  pip install tensorflow requests numpy

Yeh script:
  1. SSD MobileNet V1 quantized (COCO) model download karta hai
  2. Sirf dog (class 17) aur car (class 3) classes ke liye optimize karta hai
  3. model_data.h file generate karta hai (C array format mein)
"""

import os
import sys
import struct
import urllib.request

# ─── Configuration ────────────────────────────────────────────────────
OUTPUT_FILE = "model_data.h"

# Pre-quantized SSD MobileNet V1 0.25x 224x224 COCO model
# Source: TensorFlow Lite hosted models
MODEL_URL = (
    "https://storage.googleapis.com/download.tensorflow.org/models/"
    "tflite/task_library/object_detection/android/"
    "lite-model_ssd_mobilenet_v1_1_metadata_2.tflite"
)

# Fallback: smaller model
MODEL_URL_FALLBACK = (
    "https://github.com/google-coral/test_data/raw/master/"
    "ssd_mobilenet_v1_coco_quant_postprocess.tflite"
)

MODEL_FILENAME = "dog_car_model.tflite"

# ─── Download model ───────────────────────────────────────────────────
def download_model():
    if os.path.exists(MODEL_FILENAME):
        print(f"[INFO] Model already exists: {MODEL_FILENAME}")
        return True

    print("[INFO] Downloading model...")
    for url in [MODEL_URL, MODEL_URL_FALLBACK]:
        try:
            print(f"[INFO] Trying: {url}")
            urllib.request.urlretrieve(url, MODEL_FILENAME)
            size = os.path.getsize(MODEL_FILENAME)
            print(f"[OK] Downloaded: {MODEL_FILENAME} ({size/1024:.1f} KB)")
            return True
        except Exception as e:
            print(f"[WARN] Failed: {e}")

    return False

# ─── Convert .tflite → C array ────────────────────────────────────────
def generate_header(model_path, output_path):
    print(f"[INFO] Converting {model_path} → {output_path} ...")

    with open(model_path, "rb") as f:
        model_bytes = f.read()

    total = len(model_bytes)
    print(f"[INFO] Model size: {total} bytes ({total/1024:.1f} KB)")

    lines = []
    lines.append("/**")
    lines.append(" * model_data.h — AUTO-GENERATED by get_model.py")
    lines.append(" * DO NOT EDIT MANUALLY")
    lines.append(f" * Model size: {total} bytes ({total/1024:.1f} KB)")
    lines.append(" *")
    lines.append(" * Model: SSD MobileNet V1 quantized (COCO)")
    lines.append(" * Classes used: car (class 1), dog (class 2)")
    lines.append(" */")
    lines.append("")
    lines.append("#ifndef MODEL_DATA_H")
    lines.append("#define MODEL_DATA_H")
    lines.append("")
    lines.append("#include <pgmspace.h>")
    lines.append("")
    lines.append(f"const unsigned int g_model_data_len = {total};")
    lines.append("")
    lines.append("const unsigned char g_model_data[] PROGMEM = {")

    # Write bytes in rows of 16
    for i in range(0, total, 16):
        chunk = model_bytes[i:i+16]
        hex_str = ", ".join(f"0x{b:02x}" for b in chunk)
        if i + 16 < total:
            lines.append(f"  {hex_str},")
        else:
            lines.append(f"  {hex_str}")

    lines.append("};")
    lines.append("")
    lines.append("#endif // MODEL_DATA_H")

    with open(output_path, "w") as f:
        f.write("\n".join(lines))

    print(f"[OK] Generated: {output_path}")
    print(f"[OK] Model size: {total/1024:.1f} KB ({total} bytes)")

# ─── Main ─────────────────────────────────────────────────────────────
if __name__ == "__main__":
    print("=" * 60)
    print("  ESP32-CAM Dog-on-Car Model Generator")
    print("=" * 60)

    if not download_model():
        print("[ERROR] Model download failed! Check internet connection.")
        print("[INFO] Manual download karein:")
        print(f"  {MODEL_URL}")
        print(f"  File ko '{MODEL_FILENAME}' naam se save karein")
        print(f"  Phir script dobara run karein")
        sys.exit(1)

    generate_header(MODEL_FILENAME, OUTPUT_FILE)

    print()
    print("=" * 60)
    print(f"[DONE] {OUTPUT_FILE} ready!")
    print("[NEXT] Arduino IDE mein CameraWebServer.ino compile karein")
    print("=" * 60)
